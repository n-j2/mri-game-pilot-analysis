def pretty_label(column_name: str) -> str:
    """
    Return a readable display label for a dataframe column.
    """
    return COLUMN_LABELS.get(
        column_name,
        column_name.replace("_", " "),
    )


def load_data() -> pd.DataFrame:
    """
    Load the participant summary generated by the Excel-processing script.
    """
    if not EXCEL_FILE.exists():
        raise FileNotFoundError(
            f"Could not find Excel file: {EXCEL_FILE.resolve()}\n"
            "Run make_excel_summary_publication.py first."
        )

    dataframe = pd.read_excel(
        EXCEL_FILE,
        sheet_name=SHEET_NAME,
    )

    if dataframe.empty:
        raise RuntimeError(
            "The Excel worksheet was loaded, but it contains no "
            "participant rows."
        )

    if "meaningful_completion" not in dataframe.columns:
        raise RuntimeError(
            "Could not find required column: meaningful_completion"
        )

    return dataframe


def prepare_output_folders() -> dict[str, Path]:
    """
    Create a clean set of figure-output folders.

    If CLEAR_OLD_FIGURES is True, the previous figures directory is
    deleted first. This prevents discontinued or outdated plots from
    remaining in the output.
    """
    if CLEAR_OLD_FIGURES and FIGURES_DIR.exists():
        shutil.rmtree(FIGURES_DIR)

    folders = {
        "time": FIGURES_DIR / "time_plots",
        "pre_post": FIGURES_DIR / "pre_post_plots",
        "numeric": FIGURES_DIR / "numeric_plots",
        "aim": FIGURES_DIR / "aim_plots",
    }

    for folder in folders.values():
        folder.mkdir(
            parents=True,
            exist_ok=True,
        )

    return folders


def is_meaningful(value) -> bool:
    """
    Interpret values from the meaningful_completion Excel column.
    """
    if isinstance(value, bool):
        return value

    if pd.isna(value):
        return True

    text = str(value).strip().lower()

    if text in {"true", "1", "yes", "y"}:
        return True

    if text in {"false", "0", "no", "n"}:
        return False

    return bool(value)


def safe_numeric_series(
    dataframe: pd.DataFrame,
    column: str,
) -> pd.Series:
    """
    Convert a dataframe column to numeric values.

    Invalid values are converted to missing values.
    """
    return pd.to_numeric(
        dataframe[column],
        errors="coerce",
    )


def calculate_x_limits_from_zero(
    values: pd.Series,
) -> tuple[float, float]:
    """
    Calculate an x-axis range for duration plots.

    The substantive scale begins at zero, with a small visual margin
    on either side to prevent points at zero or at the maximum value
    from being clipped.
    """
    numeric_values = pd.to_numeric(
        values,
        errors="coerce",
    ).dropna()

    if numeric_values.empty:
        return -0.5, 1.0

    observed_maximum = float(numeric_values.max())

    if observed_maximum <= 0:
        return -0.5, 1.0

    margin = max(
        observed_maximum * 0.03,
        1.0,
    )

    return -margin, observed_maximum + margin


def scatter_points_on_line(
    axis,
    dataframe: pd.DataFrame,
    x_values: pd.Series,
    y_value: float,
    point_size: int = 45,
) -> None:
    """
    Plot participant values directly on a single horizontal line.

    Participants satisfying meaningful-completion criteria are shown
    in blue. Those not satisfying the criteria are shown in red.
    """
    values = pd.to_numeric(
        x_values,
        errors="coerce",
    )

    valid = values.notna()

    if valid.sum() == 0:
        return

    meaningful_status = dataframe[
        "meaningful_completion"
    ].apply(is_meaningful)

    meaningful_mask = valid & meaningful_status
    non_meaningful_mask = valid & ~meaningful_status

    axis.scatter(
        values[meaningful_mask],
        np.full(
            meaningful_mask.sum(),
            y_value,
        ),
        color=MEANINGFUL_COLOUR,
        s=point_size,
        alpha=0.85,
        edgecolors="black",
        linewidths=0.3,
        zorder=3,
    )

    # Plot non-meaningful completions afterwards so red points remain
    # visible where values overlap.
    axis.scatter(
        values[non_meaningful_mask],
        np.full(
            non_meaningful_mask.sum(),
            y_value,
        ),
        color=NOT_MEANINGFUL_COLOUR,
        s=point_size,
        alpha=0.95,
        edgecolors="black",
        linewidths=0.3,
        zorder=4,
    )


