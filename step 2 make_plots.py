def plot_pre_post_connected(
    dataframe: pd.DataFrame,
    pre_column: str,
    post_column: str,
    title: str,
    y_label: str,
    y_minimum: int,
    y_maximum: int,
    output_path: Path,
) -> None:
    """
    Plot paired pre-post participant values.

    Individual participant trajectories are shown as connecting lines.
    One aggregated marker is displayed at each observed pre/post value,
    with the number of participants at that value printed inside.
    """
    if (
        pre_column not in dataframe.columns
        or post_column not in dataframe.columns
    ):
        print(
            f"Missing {pre_column} or {post_column}. "
            f"Skipping {title}."
        )
        return

    pre_values = safe_numeric_series(
        dataframe,
        pre_column,
    )

    post_values = safe_numeric_series(
        dataframe,
        post_column,
    )

    valid = (
        pre_values.notna()
        & post_values.notna()
    )

    # Apply the same MCQ-specific meaningful-completion gate used for the
    # MCQ change-score bar chart. Participants must have attempted at least
    # 5 of 7 MCQ items at BOTH pre and post to appear in the MCQ trajectory
    # plot. Participants who failed meaningful completion only for another
    # reason (for example, NPC interactions < 8) remain eligible.
    #
    # Anxiety and willingness trajectory plots retain their existing
    # behaviour and require only valid paired pre/post values.
    if (
        pre_column == "pre_mcq_total_correct"
        and post_column == "post_mcq_total_correct"
    ):
        valid = (
            valid
            & get_mcq_meaningful_completion_mask(
                dataframe
            )
        )

    if valid.sum() == 0:
        print(
            f"No valid data for {title}. Skipping."
        )
        return

    figure, axis = plt.subplots(
        figsize=(5.2, 5.2)
    )

    # Draw participant-level connecting lines first.
    for participant_index in dataframe.index[valid]:
        colour = (
            MEANINGFUL_COLOUR
            if is_meaningful(
                dataframe.loc[
                    participant_index,
                    "meaningful_completion",
                ]
            )
            else NOT_MEANINGFUL_COLOUR
        )

        axis.plot(
            [0, 1],
            [
                pre_values.loc[participant_index],
                post_values.loc[participant_index],
            ],
            color=colour,
            alpha=0.28,
            linewidth=1.2,
            zorder=1,
        )

    # Draw aggregated markers for each observed score at pre and post.
    for x_position, values in [
        (0, pre_values),
        (1, post_values),
    ]:
        valid_values = values[valid]

        rounded_values = (
            valid_values
            .round()
            .astype(int)
        )

        counts_by_score = (
            rounded_values
            .value_counts()
            .sort_index()
        )

        for score, count in counts_by_score.items():
            participant_indices_at_score = rounded_values[
                rounded_values == score
            ].index

            number_meaningful = sum(
                is_meaningful(
                    dataframe.loc[
                        participant_index,
                        "meaningful_completion",
                    ]
                )
                for participant_index
                in participant_indices_at_score
            )

            number_non_meaningful = (
                count - number_meaningful
            )

            if number_non_meaningful == 0:
                marker_colour = MEANINGFUL_COLOUR

            elif number_meaningful == 0:
                marker_colour = NOT_MEANINGFUL_COLOUR

            else:
                marker_colour = "#7b3294"

            marker_size = 160 + (count - 1) * 35

            axis.scatter(
                x_position,
                score,
                color=marker_colour,
                s=marker_size,
                alpha=0.95,
                edgecolors="black",
                linewidths=0.7,
                zorder=3,
            )

            axis.text(
                x_position,
                score,
                str(count),
                ha="center",
                va="center",
                fontsize=8,
                fontweight="bold",
                color="white",
                zorder=4,
            )

    axis.set_xticks([0, 1])
    axis.set_xticklabels(["Pre", "Post"])

    axis.set_xlim(
        -0.25,
        1.25,
    )

    axis.set_ylim(
        y_minimum - 0.5,
        y_maximum + 0.5,
    )

    axis.set_yticks(
        np.arange(
            y_minimum,
            y_maximum + 1,
            1,
        )
    )

    axis.set_ylabel(y_label)
    axis.set_title(title)

    axis.grid(
        axis="y",
        alpha=0.25,
    )

    axis.spines["top"].set_visible(False)
    axis.spines["right"].set_visible(False)

    figure.tight_layout()

    figure.savefig(
        output_path,
        dpi=300,
    )

    plt.close(figure)


