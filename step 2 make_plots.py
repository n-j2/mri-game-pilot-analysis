def get_integer_change_series_preserve_index(
    values: pd.Series,
) -> pd.Series:
    """
    Convert change scores to nullable integers while preserving the
    original dataframe index.
    """
    numeric_values = pd.to_numeric(
        values,
        errors="coerce",
    )

    rounded_values = numeric_values.round()

    return rounded_values.astype("Int64")


def get_change_axis_range(
    integer_values: pd.Series,
) -> tuple[int, int]:
    """
    Determine the displayed change-score range from the observed values,
    while always including zero.
    """
    valid_values = integer_values.dropna()

    if valid_values.empty:
        return -1, 1

    observed_minimum = int(
        valid_values.min()
    )

    observed_maximum = int(
        valid_values.max()
    )

    x_minimum = min(
        observed_minimum,
        0,
    )

    x_maximum = max(
        observed_maximum,
        0,
    )

    if x_minimum == x_maximum:
        x_minimum -= 1
        x_maximum += 1

    return x_minimum, x_maximum


def get_mcq_meaningful_completion_mask(
    dataframe: pd.DataFrame,
) -> pd.Series:
    """
    Return a Boolean mask identifying participants who met the MCQ-specific
    meaningful-completion requirement: at least 5 of 7 MCQ items attempted
    at both pre- and post-game timepoints.

    The explicit pre_mcq_attempted and post_mcq_attempted columns are used
    when available. If either column is unavailable, the function falls back
    to the standardised meaningful_completion_failure_reason text generated
    by the step-1 summary script.
    """
    if (
        "pre_mcq_attempted" in dataframe.columns
        and "post_mcq_attempted" in dataframe.columns
    ):
        pre_attempted = pd.to_numeric(
            dataframe["pre_mcq_attempted"],
            errors="coerce",
        )

        post_attempted = pd.to_numeric(
            dataframe["post_mcq_attempted"],
            errors="coerce",
        )

        return (
            pre_attempted.ge(5)
            & post_attempted.ge(5)
        )

    if "meaningful_completion_failure_reason" in dataframe.columns:
        failure_reason = (
            dataframe["meaningful_completion_failure_reason"]
            .fillna("")
            .astype(str)
            .str.lower()
        )

        failed_mcq_completion = (
            failure_reason.str.contains(
                "pre mcq attempted <",
                regex=False,
            )
            | failure_reason.str.contains(
                "post mcq attempted <",
                regex=False,
            )
        )

        return ~failed_mcq_completion

    # Defensive fallback: if the MCQ-specific completion information is
    # unavailable, retain all rows and let missing change scores be excluded
    # in the usual way.
    print(
        "Warning: MCQ completion columns were not found. "
        "MCQ change plot will use all participants with valid change scores."
    )

    return pd.Series(
        True,
        index=dataframe.index,
    )


def plot_change_bar_chart(
    dataframe: pd.DataFrame,
    column: str,
    output_path: Path,
) -> None:
    """
    Plot the frequency distribution of an integer change score.

    Bars are stacked by overall meaningful-completion status.

    For the MCQ change-score plot only, participants are additionally
    required to have attempted at least 5 of 7 MCQ items at both pre- and
    post-game timepoints. Participants who failed meaningful completion
    solely for another reason (for example, NPC interactions < 8) remain
    eligible for the MCQ plot provided that their MCQ completion was
    sufficient and a valid change score is available.

    Anxiety and willingness plots retain the existing behaviour and include
    all participants with a valid change score for the respective outcome.
    """
    if column not in dataframe.columns:
        print(
            f"{column} not found. Skipping."
        )
        return

    integer_values = (
        get_integer_change_series_preserve_index(
            dataframe[column]
        )
    )

    if column == "mcq_correct_change":
        mcq_completion_mask = (
            get_mcq_meaningful_completion_mask(
                dataframe
            )
        )

        integer_values = integer_values.where(
            mcq_completion_mask
        )

    if integer_values.dropna().empty:
        print(
            f"No valid data for {column}. Skipping."
        )
        return

    x_minimum, x_maximum = get_change_axis_range(
        integer_values
    )

    x_values = list(
        range(
            x_minimum,
            x_maximum + 1,
        )
    )

    meaningful_mask = dataframe[
        "meaningful_completion"
    ].apply(is_meaningful)

    non_meaningful_mask = ~meaningful_mask

    meaningful_counts: list[int] = []
    non_meaningful_counts: list[int] = []

    for x_value in x_values:
        value_mask = (
            integer_values == x_value
        )

        meaningful_counts.append(
            int(
                (
                    value_mask
                    & meaningful_mask
                ).sum()
            )
        )

        non_meaningful_counts.append(
            int(
                (
                    value_mask
                    & non_meaningful_mask
                ).sum()
            )
        )

    stacked_totals = (
        np.array(meaningful_counts)
        + np.array(non_meaningful_counts)
    )

    maximum_count = (
        int(stacked_totals.max())
        if len(stacked_totals) > 0
        else 1
    )

    if maximum_count < 1:
        maximum_count = 1

    figure, axis = plt.subplots(
        figsize=(8, 4.2)
    )

    axis.bar(
        x_values,
        meaningful_counts,
        width=0.8,
        color=MEANINGFUL_COLOUR,
        edgecolor="black",
        linewidth=0.4,
        label="Meaningful completion",
    )

    axis.bar(
        x_values,
        non_meaningful_counts,
        width=0.8,
        bottom=meaningful_counts,
        color=NOT_MEANINGFUL_COLOUR,
        edgecolor="black",
        linewidth=0.4,
        label="Did not meet meaningful completion",
    )

    # Display the observed participant count and percentage in the centre
    # of each non-zero stacked bar. Percentages use the number of participants
    # actually eligible for and represented in this change-score plot as the
    # denominator. For MCQ this therefore excludes participants who attempted
    # fewer than 5 items at either pre or post, in addition to missing change
    # scores. Anxiety and willingness retain their existing valid-pair
    # denominators.
    valid_participant_count = int(integer_values.notna().sum())

    for x_value, total_count in zip(
        x_values,
        stacked_totals,
    ):
        if total_count <= 0:
            continue

        percentage = (
            100.0 * float(total_count) / valid_participant_count
            if valid_participant_count > 0
            else 0.0
        )

        axis.text(
            x_value,
            float(total_count) / 2.0,
            f"{int(total_count)} ({percentage:.1f}%)",
            ha="center",
            va="center",
            fontsize=7,
            fontweight="bold",
            color="white",
            clip_on=True,
            zorder=5,
        )

    axis.set_xlim(
        x_minimum - 0.7,
        x_maximum + 0.7,
    )

