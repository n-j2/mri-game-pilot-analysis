def normalise_aim_response(value) -> str:
    """
    Convert AIM responses to the standard categories used for plotting.

    Missing or blank responses are represented as not_answered.
    """
    if pd.isna(value):
        return "not_answered"

    text = str(value).strip()

    if text == "":
        return "not_answered"

    text = (
        text
        .lower()
        .replace("-", "_")
        .replace(" ", "_")
    )

    replacements = {
        "completely_disagree": "completely_disagree",
        "strongly_disagree": "completely_disagree",

        "disagree": "disagree",

        "neither": "neither_agree_nor_disagree",
        "neutral": "neither_agree_nor_disagree",
        "neither_agree_nor_disagree":
            "neither_agree_nor_disagree",
        "neither_disagree_nor_agree":
            "neither_agree_nor_disagree",

        "agree": "agree",

        "completely_agree": "completely_agree",
        "strongly_agree": "completely_agree",

        "na": "not_answered",
        "n/a": "not_answered",
        "none": "not_answered",
        "nan": "not_answered",
        "not_answered": "not_answered",
        "missing": "not_answered",
    }

    return replacements.get(
        text,
        text,
    )


def plot_all_aim_items(
    dataframe: pd.DataFrame,
    output_path: Path,
) -> None:
    """
    Plot all four AIM-item response distributions as horizontal
    proportional stacked bars.

    Missing responses are included as a separate category so every
    bar represents the full participant sample.
    """
    existing_aim_columns = [
        column
        for column in AIM_COLUMNS
        if column in dataframe.columns
    ]

    if not existing_aim_columns:
        print(
            "No AIM columns found. Skipping AIM plot."
        )
        return

    total_participants = len(dataframe)

    if total_participants == 0:
        print(
            "No participants found. Skipping AIM plot."
        )
        return

    number_of_items = len(
        existing_aim_columns
    )

    figure_height = max(
        4.6,
        number_of_items * 1.0,
    )

    figure, axis = plt.subplots(
        figsize=(10, figure_height)
    )

    y_positions = list(
        range(number_of_items)
    )[::-1]

    for aim_column, y_position in zip(
        existing_aim_columns,
        y_positions,
    ):
        responses = dataframe[
            aim_column
        ].apply(normalise_aim_response)

        counts = responses.value_counts()

        left_position = 0.0

        for category in AIM_RESPONSE_ORDER:
            number = int(
                counts.get(
                    category,
                    0,
                )
            )

            proportion = (
                number / total_participants
            )

            if number == 0:
                continue

            colour = AIM_COLOURS.get(
                category,
                "#cccccc",
            )

            axis.barh(
                y=y_position,
                width=proportion,
                left=left_position,
                height=0.72,
                color=colour,
                edgecolor="white",
                linewidth=1.0,
            )

            # Use two lines so the label fits more comfortably inside
            # narrow response-category segments.
            label = (
                f"{proportion:.0%}\n"
                f"(n={number})"
            )

            # Keep every label centred within its own segment.
            # Use progressively smaller text for narrower segments.
            if proportion >= 0.12:
                font_size = 8

            elif proportion >= 0.07:
                font_size = 7

            else:
                font_size = 6

            axis.text(
                left_position + proportion / 2,
                y_position,
                label,
                ha="center",
                va="center",
                fontsize=font_size,
                color="black",
                linespacing=0.9,
                clip_on=True,
            )

            left_position += proportion

        known_categories = set(
            AIM_RESPONSE_ORDER
        )

        unexpected_categories = sorted(
            set(counts.index)
            - known_categories
        )

        if unexpected_categories:
            print(
                "Warning: unexpected AIM categories in "
                f"{aim_column}: {unexpected_categories}"
            )

    axis.set_xlim(0, 1)

    axis.set_ylim(
        -0.7,
        number_of_items - 0.3,
    )

    axis.set_yticks(y_positions)

    axis.set_yticklabels(
        [
            pretty_label(column)
            for column in existing_aim_columns
        ]
    )

    axis.set_title(
        "AIM item response distributions"
    )

    axis.set_xticks([])
    axis.set_xlabel("")
    axis.grid(False)

    axis.spines["top"].set_visible(False)
    axis.spines["right"].set_visible(False)
    axis.spines["bottom"].set_visible(False)

    legend_handles = [
        Patch(
            facecolor=AIM_COLOURS[category],
            label=AIM_DISPLAY_LABELS[category],
        )
        for category in AIM_RESPONSE_ORDER
    ]

    axis.legend(
        handles=legend_handles,
        loc="upper center",
        bbox_to_anchor=(0.5, -0.12),
        ncol=3,
        frameon=False,
        fontsize=8,
    )

    figure.tight_layout()

    figure.savefig(
        output_path,
        dpi=300,
        bbox_inches="tight",
    )

    plt.close(figure)


