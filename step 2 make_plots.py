def plot_single_time_line(
    dataframe: pd.DataFrame,
    column: str,
    title: str,
    output_path: Path,
) -> None:
    """
    Plot one duration variable as participant points on a horizontal line.
    """
    if column not in dataframe.columns:
        print(f"{column} not found. Skipping.")
        return

    values = safe_numeric_series(
        dataframe,
        column,
    )

    if values.notna().sum() == 0:
        print(
            f"No valid values for {column}. Skipping."
        )
        return

    x_minimum, x_maximum = calculate_x_limits_from_zero(
        values
    )

    figure, axis = plt.subplots(
        figsize=(10, 2.4)
    )

    axis.hlines(
        y=0,
        xmin=0,
        xmax=x_maximum,
        color="black",
        linewidth=0.9,
        alpha=0.7,
    )

    scatter_points_on_line(
        axis=axis,
        dataframe=dataframe,
        x_values=values,
        y_value=0,
        point_size=55,
    )

    axis.set_xlim(
        x_minimum,
        x_maximum,
    )

    axis.set_ylim(
        -0.45,
        0.45,
    )

    axis.set_yticks([])

    axis.set_xlabel("Time, seconds")
    axis.set_title(title)

    axis.grid(
        axis="x",
        alpha=0.25,
    )

    axis.spines["top"].set_visible(False)
    axis.spines["right"].set_visible(False)
    axis.spines["left"].set_visible(False)

    figure.tight_layout()

    figure.savefig(
        output_path,
        dpi=300,
    )

    plt.close(figure)


def plot_time_panel(
    dataframe: pd.DataFrame,
    columns: list[str],
    title: str,
    output_path: Path,
    custom_labels: dict[str, str] | None = None,
) -> None:
    """
    Plot several duration variables together using a shared x-axis.
    """
    existing_columns = [
        column
        for column in columns
        if column in dataframe.columns
    ]

    if not existing_columns:
        print(
            f"No columns found for {title}. Skipping."
        )
        return

    all_values = pd.concat(
        [
            safe_numeric_series(
                dataframe,
                column,
            )
            for column in existing_columns
        ],
        axis=0,
    )

    if all_values.notna().sum() == 0:
        print(
            f"No valid values for {title}. Skipping."
        )
        return

    x_minimum, x_maximum = calculate_x_limits_from_zero(
        all_values
    )

    number_of_rows = len(existing_columns)
    figure_height = max(
        3.0,
        number_of_rows * 0.9,
    )

    figure, axis = plt.subplots(
        figsize=(10, figure_height)
    )

    y_positions = list(
        range(number_of_rows)
    )[::-1]

    for column, y_position in zip(
        existing_columns,
        y_positions,
    ):
        axis.hlines(
            y=y_position,
            xmin=0,
            xmax=x_maximum,
            color="black",
            linewidth=0.8,
            alpha=0.55,
        )

        scatter_points_on_line(
            axis=axis,
            dataframe=dataframe,
            x_values=dataframe[column],
            y_value=y_position,
            point_size=50,
        )

    axis.set_xlim(
        x_minimum,
        x_maximum,
    )

    axis.set_ylim(
        -0.7,
        number_of_rows - 0.3,
    )

    axis.set_yticks(y_positions)

    if custom_labels is None:
        labels = [
            pretty_label(column)
            for column in existing_columns
        ]
    else:
        labels = [
            custom_labels.get(
                column,
                pretty_label(column),
            )
            for column in existing_columns
        ]

    axis.set_yticklabels(labels)

    axis.set_xlabel("Time, seconds")
    axis.set_title(title)

    axis.grid(
        axis="x",
        alpha=0.25,
    )

    axis.spines["top"].set_visible(False)
    axis.spines["right"].set_visible(False)

    figure.tight_layout()

    figure.savefig(
        output_path,
        dpi=300,
    )

    plt.close(figure)


